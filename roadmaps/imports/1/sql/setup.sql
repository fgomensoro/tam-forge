DROP TABLE IF EXISTS sync_attempts;
DROP TABLE IF EXISTS webhook_events;
DROP TABLE IF EXISTS payments;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS customers;

CREATE TABLE customers (
    customer_id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    tier TEXT NOT NULL CHECK (tier IN ('SMB', 'MID_MARKET', 'ENTERPRISE')),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE orders (
    order_id INTEGER PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
    external_id TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    amount_cents INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('CREATED', 'PAID', 'CANCELLED', 'FULFILLED'))
);

CREATE TABLE payments (
    payment_id INTEGER PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id),
    processor_id TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('REQUIRES_ACTION', 'AUTHORIZED', 'CAPTURED', 'FAILED', 'REFUNDED')),
    amount_cents INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    settled_at TIMESTAMP NULL
);

CREATE TABLE webhook_events (
    event_id INTEGER PRIMARY KEY,
    provider_event_id TEXT NOT NULL,
    provider TEXT NOT NULL,
    event_type TEXT NOT NULL,
    order_id INTEGER NULL REFERENCES orders(order_id),
    received_at TIMESTAMP NOT NULL,
    processed_at TIMESTAMP NULL,
    status TEXT NOT NULL CHECK (status IN ('RECEIVED', 'PROCESSED', 'FAILED', 'IGNORED')),
    error_code TEXT NULL
);

CREATE TABLE sync_attempts (
    attempt_id INTEGER PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id),
    destination TEXT NOT NULL,
    attempt_no INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('SUCCESS', 'FAILED_RETRYABLE', 'FAILED_FINAL')),
    error_code TEXT NULL,
    started_at TIMESTAMP NOT NULL,
    finished_at TIMESTAMP NULL
);

